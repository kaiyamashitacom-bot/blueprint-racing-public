/** 時刻 at (枠・週の始まり) の回し方に入っている公式コース (TRACK_DEFS の順) */
export function rotationTrackDefs(at: number): TrackDef[] {
  return TRACK_DEFS.filter((d) => !((TRACK_ROTATION_FROM[d.id] ?? -Infinity) > at));
}

export function rotationTrackIds(at: number): string[] {
  return rotationTrackDefs(at).map((d) => d.id);
}

const cache = new Map<string, Track>();

/** 公開されたみんなのコースの id の頭 ("pub:12")。サーバーの AccountsDO の tracks の表の番号 */
export const PUB_TRACK_PREFIX = "pub:";

export function isPublicTrackId(id: string): boolean {
  return typeof id === "string" && id.startsWith(PUB_TRACK_PREFIX);
}

export function isOfficialTrackId(id: string): boolean {
  return TRACK_DEFS.some((d) => d.id === id);
}

/** 公式でないコース (みんなのコース) の形。registerTrackDef で入れたものだけ */
const extra = new Map<string, TrackDef>();
/** 覚えておく数 (古いものから忘れる。仮) */
const EXTRA_MAX = 64;

/**
 * 公式でないコース ("pub:<id>" など) を getTrack で引けるようにする。
 * 部屋 (サーバー) はレースの前に AccountsDO から形を読んで入れる。画面はサーバーから読んだときに入れる
 */
export function registerTrackDef(def: TrackDef): void {
  if (!def || typeof def.id !== "string" || isOfficialTrackId(def.id)) return;
  extra.delete(def.id);
  extra.set(def.id, def);
  cache.delete(def.id);
  while (extra.size > EXTRA_MAX) {
    const old = extra.keys().next().value as string;
    extra.delete(old);
    cache.delete(old);
  }
}

/** id のコースの形を知っているか (公式か、registerTrackDef で入れたもの) */
export function knownTrackDef(id: string): TrackDef | null {
  return TRACK_DEFS.find((d) => d.id === id) ?? extra.get(id) ?? null;
}

/** id のコース。知らない id は 1 本目の公式コース */
export function getTrack(id: string): Track {
  let t = cache.get(id);
  if (!t) {
    const def = knownTrackDef(id) ?? TRACK_DEFS[0];
    t = buildTrack(def);
    cache.set(def.id, t);
    cache.set(id, t);
  }
  return t;
}
